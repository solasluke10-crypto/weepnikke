#!/usr/bin/env python3
"""Builds assets/models/alice-data.js from the original Alice.obj + textures.

Usage:  python3 tools/build_alice.py <Alice.obj> <textures_dir> <out_file.js>
Needs:  pip install pillow numpy

Why a .js data file instead of loading the .obj at runtime?  Double-clicking
index.html (file://) blocks fetch() and WebGL textures from image files, so the
model and its textures are embedded as base64 and read by assets/models/alice.js.
Change TEX_SIZE / TEX_QUALITY below to trade quality for download size.
"""
import sys, io, os, json, base64, collections
import numpy as np
from PIL import Image

TEX_SIZE = 1024      # textures are shrunk to this many pixels square
TEX_QUALITY = 72     # WebP quality 0-100

def b64(arr): return base64.b64encode(arr.tobytes()).decode()

def main(obj, tex_dir, out):
    V, VT, VN = [], [], []
    groups = collections.OrderedDict()   # material -> list of (v,vt,vn) corner triples
    cur = None
    for line in open(obj):
        p = line.split()
        if not p: continue
        if p[0] == 'v':  V.append(list(map(float, p[1:4])))
        elif p[0] == 'vt': VT.append(list(map(float, p[1:3])))
        elif p[0] == 'vn': VN.append(list(map(float, p[1:4])))
        elif p[0] == 'usemtl': cur = p[1].split('/')[-1]; groups.setdefault(cur, [])
        elif p[0] == 'f':
            corners = []
            for t in p[1:]:
                a = (t.split('/') + ['', ''])[:3]
                corners.append((int(a[0]) - 1, int(a[1]) - 1 if a[1] else -1, int(a[2]) - 1 if a[2] else -1))
            for i in range(1, len(corners) - 1):   # triangulate fans
                groups[cur] += [corners[0], corners[i], corners[i + 1]]
    V = np.array(V, 'f4'); VT = np.array(VT, 'f4'); VN = np.array(VN, 'f4')
    out_groups = {}
    for name, corners in groups.items():
        remap, idx, pos, uv, nor = {}, [], [], [], []
        for c in corners:
            if c not in remap:
                remap[c] = len(pos)
                pos.append(V[c[0]]); uv.append(VT[c[1]] if c[1] >= 0 else (0, 0)); nor.append(VN[c[2]] if c[2] >= 0 else (0, 1, 0))
            idx.append(remap[c])
        pos = np.array(pos, 'f4'); uv = np.array(uv, 'f4'); nor = np.round(np.array(nor) * 127).astype('i1')
        idx = np.array(idx, 'u2' if len(pos) < 65536 else 'u4')
        out_groups[name] = dict(count=len(pos), index16=bool(idx.dtype == np.uint16), pos=b64(pos), uv=b64(uv), nor=b64(nor), idx=b64(idx))
    # merge duplicate material names (Coat/Bottom appear in several objects) - already merged by name above
    tex = {}
    for name in out_groups:
        files = {f.lower(): f for f in os.listdir(tex_dir)}   # texture names differ in capitalisation (hairBack.png vs HairBack)
        im = Image.open(f'{tex_dir}/' + files[name.lower() + '.png']).convert('RGB')   # all of Alice's textures are fully opaque, so the alpha channel is dropped.resize((TEX_SIZE, TEX_SIZE), Image.LANCZOS)
        buf = io.BytesIO(); im.save(buf, 'WEBP', quality=TEX_QUALITY, method=6)
        tex[name] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    mn, mx = V.min(0).tolist(), V.max(0).tolist()
    # the model is pivoted on the middle of her shoes (x,z) so she stands on her spot instead of her hair-centred bounding box
    shoes = np.array([V[i] for g in groups if g == 'Shoe' for i in {c[0] for c in groups[g]}])
    pivot = [float((shoes[:, 0].min() + shoes[:, 0].max()) / 2), float((shoes[:, 2].min() + shoes[:, 2].max()) / 2)]
    data = dict(bounds=dict(min=mn, max=mx), pivot=pivot, parts=out_groups, textures=tex)
    with open(out, 'w') as f:
        f.write('/* GENERATED by tools/build_alice.py - do not edit by hand. */\nwindow.ALICE_DATA=' + json.dumps(data, separators=(',', ':')) + ';\n')
    print({k: (v['count'], len(v['idx'])) for k, v in out_groups.items()}, 'bounds', mn, mx)

if __name__ == '__main__': main(*sys.argv[1:4])
